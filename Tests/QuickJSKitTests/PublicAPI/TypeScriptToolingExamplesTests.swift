    @Test("workspace artifacts are deterministic and safe to regenerate")
    func workspaceIsManaged() async throws {
        let runtime = try JavaScriptRuntime()
        try await runtime.function("answer") { () -> Int in 42 }
        let environment = try await runtime.environmentDescription()
        let workspace = try environment.typeScriptWorkspace(
            options: .init(
                sourceGlobs: ["Scripts/**/*.js", "Scripts/**/*.ts"],
                checkJavaScript: true,
                includePackageJSON: true
            )
        )

        #expect(workspace.files.map(\.path) == [
            "package.json",
            "quickjskit.generated.d.ts",
            "quickjskit.generated.d.ts.map",
            "tsconfig.json",
        ])
        #expect(workspace.files.first { $0.path == "tsconfig.json" }?.contents.contains(
            "\"checkJs\": true"
        ) == true)

        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent(UUID().uuidString, isDirectory: true)
        defer { try? FileManager.default.removeItem(at: directory) }
        try workspace.write(to: directory)
