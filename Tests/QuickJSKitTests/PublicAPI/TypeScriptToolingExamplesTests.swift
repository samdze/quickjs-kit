    @Test("snapshots are detached and independent runtimes render identically")
    func snapshotsAreDetachedAndDeterministic() async throws {
        var firstRuntime: JavaScriptRuntime? = try JavaScriptRuntime()
        let secondRuntime = try JavaScriptRuntime()
        weak let releasedRuntime = firstRuntime

        try await firstRuntime?.global.set("one", forProperty: "alpha")
        try await firstRuntime?.global.set(2, forProperty: "beta")
        try await firstRuntime?.defineModule("ordered") { module in
            module.value(2, as: "beta")
            module.value("one", as: "alpha")
        }
        try await secondRuntime.global.set(2, forProperty: "beta")
        try await secondRuntime.global.set("one", forProperty: "alpha")
        try await secondRuntime.defineModule("ordered") { module in
            module.value("one", as: "alpha")
            module.value(2, as: "beta")
        }

        let first = try await firstRuntime?.environmentDescription()
        let second = try await secondRuntime.environmentDescription()
        firstRuntime = nil
        await Task.yield()

        #expect(releasedRuntime == nil)
        #expect(try #require(first).typeScriptDeclarations() == second.typeScriptDeclarations())
    }

    @Test("workspace regeneration removes only unchanged obsolete files")
    func workspaceRemovesOnlyOwnedObsoleteFiles() async throws {
        let runtime = try JavaScriptRuntime()
        let environment = try await runtime.environmentDescription()
        let withPackage = try environment.typeScriptWorkspace(
            options: .init(includePackageJSON: true)
        )
        let withoutPackage = try environment.typeScriptWorkspace()
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent(UUID().uuidString, isDirectory: true)
        defer { try? FileManager.default.removeItem(at: directory) }

        try withPackage.write(to: directory)
        let unrelated = directory.appendingPathComponent("notes.txt")
        try "keep".write(to: unrelated, atomically: true, encoding: .utf8)
        try withoutPackage.write(to: directory)
        #expect(!FileManager.default.fileExists(
            atPath: directory.appendingPathComponent("package.json").path
        ))
        #expect(FileManager.default.fileExists(atPath: unrelated.path))

        try withPackage.write(to: directory)
        let package = directory.appendingPathComponent("package.json")
        try "modified".write(to: package, atomically: true, encoding: .utf8)
        try withoutPackage.write(to: directory)
        #expect(try String(contentsOf: package, encoding: .utf8) == "modified")
    }

