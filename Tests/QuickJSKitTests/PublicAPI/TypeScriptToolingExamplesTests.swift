    @Test("a runtime snapshot renders typed globals deterministically")
    func snapshotRendersTypedGlobals() async throws {
        let runtime = try JavaScriptRuntime()
        try await runtime.function(
            "loadUser",
            options: .init(
                parameterNames: ["id", "nickname"],
                documentation: "Loads a user."
            )
        ) { (_: Int64, _: String?) async throws -> User? in
